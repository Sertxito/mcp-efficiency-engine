function atomicWrite(filePath, contents) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const temporary = `${filePath}.${process.pid}.${crypto.randomUUID()}.tmp`;
  try {
    fs.writeFileSync(temporary, contents, "utf8");
    fs.renameSync(temporary, filePath);
  } catch (error) {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
    throw error;
  }
}

function assertNoSymlinkAncestors(projectRoot, absolutePath) {
  const root = path.resolve(projectRoot);
  const resolved = path.resolve(absolutePath);
  const relative = path.relative(root, resolved);
  if (relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    throw new Error(`Path escapes the project root: ${absolutePath}`);
  }
  let current = root;
  for (const segment of relative.split(path.sep).filter(Boolean)) {
    current = path.join(current, segment);
    if (!fs.existsSync(current)) break;
    if (fs.lstatSync(current).isSymbolicLink()) {
      throw new Error(`Refusing to follow a symbolic link inside the project: ${current}`);
    }
  }
}

function atomicProjectWrite(projectRoot, relative, contents) {
  const destination = path.join(projectRoot, relative);
  assertGeneratedTarget(projectRoot, relative);
  atomicWrite(destination, contents);
}

function assertGeneratedTarget(projectRoot, relative) {
  const destination = path.join(projectRoot, relative);
  assertNoSymlinkAncestors(projectRoot, destination);
  if (fs.existsSync(destination) && !isOwnedOutput(destination, "extracted")) {
    throw new Error(`Refusing to overwrite non-MCPEE project artifact: ${relative}`);
  }
}

function isOwnedOutput(filePath, kind) {
  if (!fs.existsSync(filePath)) return false;
  const contents = fs.readFileSync(filePath, "utf8");
  if (kind === "normalized") return contents.startsWith(GENERATED_MARKER);
  try {
    return JSON.parse(contents).generated_by === "mcpee";
  } catch {
    return false;
  }
}

function writeGenerated(projectRoot, relative, contents, kind) {
  const destination = path.join(projectRoot, relative);
  assertNoSymlinkAncestors(projectRoot, destination);
  if (fs.existsSync(destination) && !isOwnedOutput(destination, kind)) {
    throw new Error(`Refusing to overwrite non-MCPEE generated artifact: ${relative}`);
  }
  atomicWrite(destination, contents);
}

function removePreviousOutputs(projectRoot, previous) {
  if (!previous) return;
  const outputs = {
    normalized_path: { kind: "normalized", prefix: "knowledge/normalized/" },
    extracted_path: { kind: "extracted", prefix: "knowledge/extracted/" },
    traceability_path: { kind: "traceability", prefix: "knowledge/traceability/" },
  };
  for (const [key, { kind, prefix }] of Object.entries(outputs)) {
    const output = previous[key];
    if (typeof output !== "string") continue;
    const normalizedOutput = output.replace(/\\/g, "/");
    if (!normalizedOutput.startsWith(prefix)) {
      throw new Error(`Invalid generated artifact path in previous source manifest: ${output}`);
    }
    const absolute = path.resolve(projectRoot, output);
    assertNoSymlinkAncestors(projectRoot, absolute);
    if (absolute.startsWith(`${path.resolve(projectRoot)}${path.sep}`) && isOwnedOutput(absolute, kind)) {
      fs.unlinkSync(absolute);
    }
  }
}

function safeSourceText(buffer) {
  if (buffer.includes(0)) return { status: "skipped-binary", text: null };
  const text = buffer.toString("utf8").replace(/^\uFEFF/, "");
  if (text.includes("\uFFFD")) return { status: "skipped-non-utf8", text: null };
  return { status: "processed", text };
}

function headings(text) {
  return [...text.matchAll(/^\s{0,3}(#{1,6})\s+(.+?)\s*#*\s*$/gm)]
    .map((match) => ({
      level: match[1].length,
      title: match[2].trim(),
      line: text.slice(0, match.index).split("\n").length,
    }));
}

function codeSymbolEvidence(text, category) {
  if (category !== "source-code" && category !== "tests") return [];
  const pattern = /^\s*(?:export\s+)?(?:async\s+)?(?:function|class|interface|type|enum|def|func|struct|trait)\s+([A-Za-z_$][\w$]*)/gm;
  return [...text.matchAll(pattern)].slice(0, 500).map((match) => ({
    name: match[1],
    line: text.slice(0, match.index).split("\n").length,
  }));
}

function parseDelimitedFields(line, delimiter) {
  const fields = [];
  let value = "";
  let quoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const character = line[index];
    if (quoted) {
      if (character === '"' && line[index + 1] === '"') {
        value += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        value += character;
      }
    } else if (character === delimiter) {
      fields.push(value.trim());
      value = "";
    } else if (character === '"' && value.trim() === "") {
      quoted = true;
    } else if (character === '"') {
      return null;
    } else {
      value += character;
    }
  }
  if (quoted) return null;
  fields.push(value.trim());
  return fields;
}

function markdownTableFields(text) {
  const lines = text.split("\n");
  const fields = [];
  const cells = (line) => {
    const trimmed = line.trim().replace(/^\|/, "").replace(/\|$/, "");
    const output = [];
    let cell = "";
    for (let index = 0; index < trimmed.length; index += 1) {
      if (trimmed[index] === "\\" && trimmed[index + 1] === "|") {
        cell += "|";
        index += 1;
      } else if (trimmed[index] === "|") {
        output.push(cell.trim());
        cell = "";
      } else {
        cell += trimmed[index];
      }
    }
    output.push(cell.trim());
    return output;
  };
  for (let index = 0; index < lines.length - 1; index += 1) {
    const header = lines[index].trim();
    const separator = lines[index + 1].trim();
    if (!header.includes("|") || !separator.includes("|")) continue;
    const headers = cells(header);
    const separatorCells = cells(separator);
    if (headers.length !== separatorCells.length ||
        separatorCells.some((cell) => !/^:?-{3,}:?$/.test(cell))) continue;
    fields.push(...headers.flatMap((name, position) =>
      name ? [{ name: name.slice(0, 500), line: index + 1, position }] : []));
    index += 1;
  }
  return fields;
}

function tabularFields(text, sourcePath) {
  const extension = path.posix.extname(sourcePath).toLowerCase();
  if (extension === ".md") return markdownTableFields(text);
  if (extension !== ".csv" && extension !== ".tsv") return [];
  const lines = text.split("\n");
  const lineIndex = lines.findIndex((line) => line.trim());
  if (lineIndex === -1) return [];
  const fields = parseDelimitedFields(lines[lineIndex], extension === ".tsv" ? "\t" : ",");
  if (!fields) return [];
  return fields.flatMap((name, position) =>
    name ? [{ name: name.slice(0, 500), line: lineIndex + 1, position }] : []);
}

function tokenTerms(text) {
  const counts = new Map();
  const tokens = text.toLowerCase().match(/[\p{L}\p{N}_-]{2,}/gu) || [];
  for (const token of tokens) counts.set(token, (counts.get(token) || 0) + 1);
  return [...counts.entries()].sort(([left], [right]) => left.localeCompare(right));
}

function loadPreviousManifest(filePath) {
  if (!fs.existsSync(filePath)) return new Map();
  const parsed = JSON.parse(fs.readFileSync(filePath, "utf8"));
  if (parsed.generated_by !== "mcpee" || !Array.isArray(parsed.sources)) {
    throw new Error(`Invalid or non-MCPEE source manifest: ${filePath}`);
  }
  return new Map(parsed.sources.map((source) => [source.path, source]));
}

function derivedArtifactsAreCurrent(projectRoot, source, previous, digest, paths) {
  if (!previous || previous.sha256 !== digest ||
      previous.normalized_path !== paths.normalized_path ||
      previous.extracted_path !== paths.extracted_path ||
      previous.traceability_path !== paths.traceability_path) return false;
  const files = [
    [paths.normalized_path, "normalized"],
    [paths.extracted_path, "extracted"],
    [paths.traceability_path, "traceability"],
  ];
  for (const [relative, kind] of files) {
    const absolute = path.join(projectRoot, relative);
    assertNoSymlinkAncestors(projectRoot, absolute);
    if (!fs.existsSync(absolute) || !isOwnedOutput(absolute, kind)) return false;
  }
  const normalized = fs.readFileSync(path.join(projectRoot, paths.normalized_path), "utf8");
  const extractedText = fs.readFileSync(path.join(projectRoot, paths.extracted_path), "utf8");
  const traceabilityText = fs.readFileSync(path.join(projectRoot, paths.traceability_path), "utf8");
  let metadata;
  let traceability;
  try {
    metadata = JSON.parse(extractedText);
    traceability = JSON.parse(traceabilityText);
  } catch (error) {
    if (error instanceof SyntaxError) return false;
    throw error;
  }
  return metadata.generated_by === "mcpee" &&
    metadata.source_path === source.path &&
    metadata.category === source.category &&
    metadata.processor === source.processor &&
    metadata.sha256 === digest &&
    metadata.normalized_sha256 === sha256(normalized) &&
    traceability.generated_by === "mcpee" &&
    traceability.source?.path === source.path &&
    traceability.source?.sha256 === digest &&
    traceability.derived?.normalized === paths.normalized_path &&
    traceability.derived?.normalized_sha256 === sha256(normalized) &&
    traceability.derived?.extracted === paths.extracted_path &&
    traceability.derived?.extracted_sha256 === sha256(extractedText);
}

function cleanupStaleArtifacts(projectRoot, previousSources, currentPaths) {
  const ownedDirectories = new Set([
    "knowledge/normalized/",
    "knowledge/extracted/",
    "knowledge/traceability/",
  ]);
  const removed = [];
  for (const source of previousSources.values()) {
    if (currentPaths.has(source.path)) continue;
    for (const key of ["normalized_path", "extracted_path", "traceability_path"]) {
      const output = source[key];
      if (typeof output !== "string" || ![...ownedDirectories].some((prefix) => output.startsWith(prefix))) continue;
      const absolute = path.resolve(projectRoot, output);
      const kind = key === "normalized_path" ? "normalized" : key === "extracted_path" ? "extracted" : "traceability";
      if (!absolute.startsWith(`${path.resolve(projectRoot)}${path.sep}`)) continue;
      assertNoSymlinkAncestors(projectRoot, absolute);
      if (isOwnedOutput(absolute, kind)) {
        fs.unlinkSync(absolute);
        removed.push(output);
      }
    }
  }
  return removed;
}

function collectSources(projectRoot, config) {
  const sources = new Map();
  const project = path.resolve(projectRoot);
  for (const configuredRoot of config.sourceRoots) {
    const absoluteRoot = path.resolve(project, configuredRoot);
    if (absoluteRoot !== project && !absoluteRoot.startsWith(`${project}${path.sep}`)) {
      throw new Error(`Source root must stay inside the project: ${configuredRoot}`);
    }
    if (!fs.existsSync(absoluteRoot)) continue;
    assertNoSymlinkAncestors(project, absoluteRoot);
    const rootStat = fs.lstatSync(absoluteRoot);
    if (rootStat.isSymbolicLink() || !rootStat.isDirectory()) continue;
    function visit(directory) {
      for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
        const absolute = path.join(directory, entry.name);
        const relative = relativePath(project, absolute);
        if (matchesIgnore(relative, entry.name, config.ignore)) continue;
        if (entry.isSymbolicLink()) continue;
        if (relative.startsWith("specs/") && isScaffolding(project, relative)) continue;
        if (entry.isDirectory()) {
          visit(absolute);
          continue;
        }
        if (!entry.isFile() || SECRET_FILE.test(relative) || PRIVATE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) continue;
        const category = classifySource(relative);
        if (category === "unknown") continue;
        const stat = fs.statSync(absolute);
        sources.set(relative, {
          path: relative,
          category,
          processor: DOCUMENT_EXTENSIONS.has(path.extname(entry.name).toLowerCase())
            ? processorFor("office-documents") : processorFor(category),
          size_bytes: stat.size,
          modified_at: stat.mtime.toISOString(),
        });
      }
    }
    visit(absoluteRoot);
  }
  return [...sources.values()].sort((a, b) => a.path.localeCompare(b.path));
}

function processSource(projectRoot, source, previous, tools) {
  const absoluteSource = path.join(projectRoot, ...source.path.split("/"));
  assertNoSymlinkAncestors(projectRoot, absoluteSource);
  const stat = fs.statSync(absoluteSource);
  if (stat.size > MAX_SOURCE_BYTES) {
    removePreviousOutputs(projectRoot, previous);
    return { ...source, status: "skipped-too-large", bytes: stat.size };
  }
  const buffer = fs.readFileSync(absoluteSource);
  const id = stableId(source.path);
  const paths = outputPaths(id);
  const digest = sha256(buffer);
  if (derivedArtifactsAreCurrent(projectRoot, source, previous, digest, paths)) {
    return { ...previous, status: "unchanged", modified_at: source.modified_at };
  }
  let decoded = safeSourceText(buffer);
  let toolUsed = null;
  if (source.processor === "office-documents") {
    const tool = tools.find((candidate) => candidate.id === "markitdown");
    if (!tool?.invokable) {
      removePreviousOutputs(projectRoot, previous);
      return {
        ...source,
        status: "requires-tool",
        required_tool: "markitdown",
        bytes: buffer.length,
        sha256: digest,
        ...(tool?.available ? { reason: "installed as a shell wrapper that MCPEE will not launch" } : {}),
      };
    }
    const result = invokeTool(projectRoot, "markitdown", [absoluteSource], { timeoutMs: 30_000 });
    if (result.status !== "success") {
      removePreviousOutputs(projectRoot, previous);
      return {
        ...source,
        status: "failed",
        error: result.error || result.stderr.trim() || `markitdown exited with code ${result.exit_code}`,
        bytes: buffer.length,
        sha256: digest,
      };
    }
    if (!result.stdout.trim()) {
      removePreviousOutputs(projectRoot, previous);
      return {
        ...source,
        status: "failed",
        error: "markitdown completed without producing Markdown on stdout",
        bytes: buffer.length,
        sha256: digest,
      };
    }
    decoded = { status: "processed", text: result.stdout };
    toolUsed = "markitdown";
  }
  if (decoded.status !== "processed") {
    removePreviousOutputs(projectRoot, previous);
    return { ...source, status: decoded.status, bytes: buffer.length, sha256: digest };
  }
  let text = decoded.text.replace(/\r\n?/g, "\n");
  if (source.path.endsWith(".ipynb")) {
    try {
      const notebook = JSON.parse(text);
      text = (notebook.cells || []).map((cell) =>
        Array.isArray(cell.source) ? cell.source.join("") : String(cell.source || "")).join("\n\n");
    } catch (error) {
      removePreviousOutputs(projectRoot, previous);
      return { ...source, status: "failed", error: `Invalid notebook JSON: ${error.message}`, bytes: buffer.length, sha256: digest };
    }
  }
  const sanitizedText = require("../../core/src/telemetry").redact(text);
  const extractedTableFields = tabularFields(sanitizedText, source.path);
  const extractedSymbols = codeSymbolEvidence(sanitizedText, source.category);
  const metadata = {
    schema_version: 1,
    generated_by: "mcpee",
    source_path: source.path,
    category: source.category,
    processor: source.processor,
    sha256: digest,
    bytes: buffer.length,
    lines: sanitizedText.length ? sanitizedText.split("\n").length : 0,
    headings: headings(sanitizedText),
    symbols: extractedSymbols.map((symbol) => symbol.name),
    ...(extractedSymbols.length
      ? { symbol_locations: extractedSymbols }
      : {}),
    ...(extractedTableFields.length
      ? {
        tabular_fields: extractedTableFields.slice(0, 500),
        ...(extractedTableFields.length > 500
          ? { tabular_fields_truncated: true }
          : {}),
      }
      : {}),
    ...(toolUsed ? { tool: toolUsed } : {}),
    generated_at: new Date().toISOString(),
  };
  const normalized = [
    GENERATED_MARKER,
    `<!-- Source: ${source.path.replace(/--/g, "- -")} -->`,
    `<!-- SHA-256: ${digest} -->`,
    "",
    source.category === "documentation" || source.category === "business" ||
      source.category === "architecture" || source.category === "external" ||
      source.category === "office-documents"
      ? sanitizedText
      : `# ${path.posix.basename(source.path)}\n\n> Source: \`${source.path}\`  \n> Category: \`${source.category}\`  \n> SHA-256: \`${digest}\`\n\n\`\`\`${path.posix.extname(source.path).slice(1)}\n${sanitizedText.replace(/```/g, "` ` `")}\n\`\`\`\n`,
  ].join("\n");
  metadata.normalized_sha256 = sha256(normalized);
  const extractedText = `${JSON.stringify(metadata, null, 2)}\n`;
  const traceabilityText = `${JSON.stringify({
    schema_version: 1,
    generated_by: "mcpee",
    source: { path: source.path, sha256: digest, modified_at: source.modified_at },
    derived: {
      normalized: paths.normalized_path,
      normalized_sha256: metadata.normalized_sha256,
      extracted: paths.extracted_path,
      extracted_sha256: sha256(extractedText),
    },
    evidence: { line_count: metadata.lines, locator_format: "source-path#line" },
  }, null, 2)}\n`;
  for (const [relative, kind] of [
    [paths.normalized_path, "normalized"],
    [paths.extracted_path, "extracted"],
    [paths.traceability_path, "traceability"],
  ]) {
    const destination = path.join(projectRoot, relative);
    assertNoSymlinkAncestors(projectRoot, destination);
    if (fs.existsSync(destination) && !isOwnedOutput(destination, kind)) {
      throw new Error(`Refusing to overwrite non-MCPEE generated artifact: ${relative}`);
    }
  }
  writeGenerated(projectRoot, paths.normalized_path, normalized, "normalized");
  writeGenerated(projectRoot, paths.extracted_path, extractedText, "extracted");
  writeGenerated(projectRoot, paths.traceability_path, traceabilityText, "traceability");
  return {
    ...source,
    ...paths,
    status: "processed",
    bytes: buffer.length,
    sha256: digest,
    lines: metadata.lines,
    headings: metadata.headings.length,
    symbols: metadata.symbols.length,
  };
}

function buildLexicalIndex(projectRoot, processed) {
  const documents = [];
  const postings = Object.create(null);
  for (const source of processed) {
    if (!source.normalized_path || !["processed", "unchanged"].includes(source.status)) continue;
    const absolute = path.join(projectRoot, source.normalized_path);
    if (!fs.existsSync(absolute)) continue;
    const terms = tokenTerms(fs.readFileSync(absolute, "utf8"));
    documents.push({
      source_id: stableId(source.path),
      source_path: source.path,
      file_name: path.posix.basename(source.path),
      modified_at: source.modified_at || null,
      normalized_path: source.normalized_path,
      sha256: source.sha256,
    });
    for (const [term, frequency] of terms) {
      if (!postings[term]) postings[term] = [];
      postings[term].push({ source_id: stableId(source.path), frequency });
    }
  }
  return {
    schema_version: 1,
    generated_by: "mcpee",
    generated_at: new Date().toISOString(),
    strategy: "local-lexical",
    document_count: documents.length,
    documents,
    postings,
  };
}

function syncProject(projectRoot, options = {}) {
  const root = path.resolve(projectRoot);
  const statePath = path.join(root, ".mcpee/state/project.json");
  if (!fs.existsSync(statePath)) throw new Error("Project is not initialized. Run mcpee init first.");
  for (const output of [
    ".mcpee/state/project.json",
    ".mcpee/indexes/source-inventory.json",
    ".mcpee/indexes/knowledge-index.json",
    "knowledge/traceability/source-manifest.json",
  ]) assertGeneratedTarget(root, output);
  const manifestPath = path.join(root, "knowledge/traceability/source-manifest.json");
  const previous = loadPreviousManifest(manifestPath);
  const config = parseConfig(root);
  const discovered = collectSources(root, config);
  const tools = options.tools || (discovered.some((source) => source.processor === "office-documents")
    ? discoverTools(root).tools
    : []);
  const currentPaths = new Set(discovered.map((source) => source.path));
  const sources = [];
  const counts = { processed: 0, unchanged: 0, "requires-tool": 0, skipped: 0, failed: 0 };
  for (const source of discovered) {
    try {
      const result = processSource(root, source, options.force ? null : previous.get(source.path), tools);
      sources.push(result);
      if (result.status === "processed" || result.status === "unchanged") counts[result.status] += 1;
      else if (result.status === "requires-tool") counts["requires-tool"] += 1;
      else if (result.status === "failed") counts.failed += 1;
      else counts.skipped += 1;
    } catch (error) {
      const failure = { ...source, status: "failed", error: error.message };
      sources.push(failure);
      counts.failed += 1;
    }
  }
  const removed = cleanupStaleArtifacts(root, previous, currentPaths);
  const generatedAt = new Date().toISOString();
  const manifest = { schema_version: 1, generated_by: "mcpee", generated_at: generatedAt, sources };
  const lexicalIndex = buildLexicalIndex(root, sources);
  lexicalIndex.generated_by = "mcpee";
  const sourceInventory = {
    schema_version: 1,
    generated_by: "mcpee",
    generated_at: generatedAt,
    roots: config.sourceRoots,
    discovered_files: discovered.length,
    counts,
    removed_derived_artifacts: removed.length,
    sources,
  };
  const state = JSON.parse(fs.readFileSync(statePath, "utf8"));
  state.last_sync = generatedAt;
  state.inventory = {
    discovered_files: discovered.length,
    processed_files: counts.processed + counts.unchanged,
    status: counts.failed > 0 ? "completed-with-errors" : "completed",
  };

  atomicProjectWrite(root, "knowledge/traceability/source-manifest.json", `${JSON.stringify(manifest, null, 2)}\n`);
  atomicProjectWrite(root, ".mcpee/indexes/source-inventory.json", `${JSON.stringify(sourceInventory, null, 2)}\n`);
  atomicProjectWrite(root, ".mcpee/indexes/knowledge-index.json", `${JSON.stringify(lexicalIndex, null, 2)}\n`);
  atomicProjectWrite(root, ".mcpee/state/project.json", `${JSON.stringify(state, null, 2)}\n`);
  const unifiedGraph = buildUnifiedGraph(root);
  const specifications = discoverBrownfieldSpec(root);
  const graphifyOptions = options.graphify ||
    (Array.isArray(options.tools)
      ? { installed: options.tools.some((tool) => tool.id === "graphify" && tool.invokable) }
      : {});
  const graphify = updateGraphifyGraph(root, graphifyOptions);
  const catalog = renderCatalog(root);
  const documentation = options.generateDocumentation === false
    ? { counts: { written: 0, preserved: 0, unchanged: 0 }, files: [] }
    : generateProjectDocumentation(root);
  recordEvent(root, {
    event_name: "knowledge.sync.completed",
    attributes: {
      discovered_files: discovered.length,
      processed: counts.processed,
      unchanged: counts.unchanged,
      failed: counts.failed,
      requires_tool: counts["requires-tool"],
      removed_derived_artifacts: removed.length,
      unified_graph_nodes: unifiedGraph.node_count,
      unified_graph_edges: unifiedGraph.edge_count,
      graphify_status: graphify.status,
      graphify_nodes: graphify.node_count || 0,
      graphify_edges: graphify.edge_count || 0,
      catalog_created: catalog.counts.created,
      catalog_updated: catalog.counts.updated,
      catalog_preserved: catalog.counts.preserved,
      documentation_written: documentation.counts.written,
      documentation_preserved: documentation.counts.preserved,
      specification_status: specifications.status,
      specification_sources: specifications.sourceCount,
    },
  });
  return {
    counts,
    discoveredFiles: discovered.length,
    removed,
    sources,
    generatedAt,
    catalog,
    documentation,
    unifiedGraph,
    graphify,
    specifications,
  };
}

function searchKnowledge(projectRoot, query, limit = 10) {
  if (typeof query !== "string" || query.trim().length === 0) throw new Error("Search query must not be empty");
  if (!Number.isInteger(limit) || limit < 1 || limit > 100) throw new Error("Search limit must be an integer between 1 and 100");
  const indexPath = path.join(projectRoot, ".mcpee/indexes/knowledge-index.json");
  if (!fs.existsSync(indexPath)) throw new Error("Knowledge index is missing. Run mcpee sync first.");
  const index = JSON.parse(fs.readFileSync(indexPath, "utf8"));
  const terms = tokenTerms(query).map(([term]) => term);
  const scores = new Map();
  for (const term of terms) {
    for (const posting of Object.hasOwn(index.postings, term) ? index.postings[term] : []) {
      scores.set(posting.source_id, (scores.get(posting.source_id) || 0) + posting.frequency);
    }
  }
  const byId = new Map(index.documents.map((document) => [document.source_id, document]));
  return [...scores.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, limit)
    .map(([id, score]) => ({ ...byId.get(id), score }));
}

function searchKnowledgeVector(projectRoot, query, limit = 10) {
  if (typeof query !== "string" || query.trim().length === 0) throw new Error("Search query must not be empty");
  if (!Number.isInteger(limit) || limit < 1 || limit > 100) throw new Error("Search limit must be an integer between 1 and 100");
  const indexPath = path.join(projectRoot, ".mcpee/indexes/knowledge-index.json");
  if (!fs.existsSync(indexPath)) throw new Error("Knowledge index is missing. Run mcpee sync first.");
  const index = JSON.parse(fs.readFileSync(indexPath, "utf8"));
  if (index.generated_by !== "mcpee" || !Array.isArray(index.documents) ||
      !index.postings || typeof index.postings !== "object" || Array.isArray(index.postings)) {
    throw new Error(`Invalid or non-MCPEE knowledge index: ${indexPath}`);
  }
  const documentCount = index.documents.length;
  if (documentCount === 0) return [];
  const queryTerms = tokenTerms(query);
  const queryWeights = new Map();
  let queryNormSquared = 0;
  for (const [term, frequency] of queryTerms) {
    const postings = Object.hasOwn(index.postings, term) ? index.postings[term] : [];
    const inverseFrequency = Math.log((documentCount + 1) / (postings.length + 1)) + 1;
    const weight = (1 + Math.log(frequency)) * inverseFrequency;
    queryWeights.set(term, weight);
    queryNormSquared += weight ** 2;
  }
  if (queryNormSquared === 0) return [];

  const documentNorms = new Map();
  for (const [term, postings] of Object.entries(index.postings)) {
    const inverseFrequency = Math.log((documentCount + 1) / (postings.length + 1)) + 1;
    for (const posting of postings) {
      const weight = (1 + Math.log(posting.frequency)) * inverseFrequency;
      documentNorms.set(posting.source_id, (documentNorms.get(posting.source_id) || 0) + weight ** 2);
    }
  }
  const scores = new Map();
  for (const [term, queryWeight] of queryWeights) {
    const postings = Object.hasOwn(index.postings, term) ? index.postings[term] : [];
    const inverseFrequency = Math.log((documentCount + 1) / (postings.length + 1)) + 1;
    for (const posting of postings) {
      const documentWeight = (1 + Math.log(posting.frequency)) * inverseFrequency;
      scores.set(posting.source_id, (scores.get(posting.source_id) || 0) + queryWeight * documentWeight);
    }
  }
  const documentsById = new Map(index.documents.map((document) => [document.source_id, document]));
  const queryNorm = Math.sqrt(queryNormSquared);
  return [...scores.entries()]
    .map(([id, score]) => ({
      ...documentsById.get(id),
      score: score / (queryNorm * Math.sqrt(documentNorms.get(id) || 1)),
    }))
    .filter((result) => result.source_path)
    .sort((left, right) => right.score - left.score || left.source_path.localeCompare(right.source_path))
    .slice(0, limit);
}

