function loadProcessorMap() {
  const catalog = JSON.parse(fs.readFileSync(PROCESSOR_CATALOG_PATH, "utf8"));
  if (catalog.schema_version !== 1 || !Array.isArray(catalog.processors)) {
    throw new Error(`Invalid source processor catalog: ${PROCESSOR_CATALOG_PATH}`);
  }
  const processorsByCategory = new Map();
  for (const processor of catalog.processors) {
    if (typeof processor.id !== "string" || !Array.isArray(processor.categories) ||
        processor.categories.length === 0 ||
        processor.categories.some((category) => typeof category !== "string") ||
        !Array.isArray(processor.formats) || processor.formats.length === 0 ||
        processor.formats.some((format) => typeof format !== "string") ||
        !Array.isArray(processor.outputs) || processor.outputs.length === 0 ||
        processor.outputs.some((output) => typeof output !== "string") ||
        !["local", "local-tool-required"].includes(processor.mode) ||
        (processor.mode === "local-tool-required" && typeof processor.tool !== "string")) {
      throw new Error(`Invalid source processor definition in ${PROCESSOR_CATALOG_PATH}`);
    }
    for (const category of processor.categories) {
      if (processorsByCategory.has(category)) {
        throw new Error(`Source category is assigned to multiple processors: ${category}`);
      }
      processorsByCategory.set(category, processor.id);
    }
  }
  return processorsByCategory;
}

const PROCESSOR_BY_CATEGORY = loadProcessorMap();

function sha256(content) {
  return crypto.createHash("sha256").update(content).digest("hex");
}

function relativePath(root, absolute) {
  return path.relative(root, absolute).split(path.sep).join("/");
}

function parseConfig(projectRoot) {
  const configPath = path.join(projectRoot, "mcpee.config.yml");
  const defaults = {
    sourceRoots: ["."],
    ignore: [...DEFAULT_IGNORES],
  };
  if (!fs.existsSync(configPath)) return defaults;
  const lines = fs.readFileSync(configPath, "utf8").split(/\r?\n/);
  let section = "";
  let listKey = "";
  const config = { sourceRoots: [], ignore: [] };
  for (const line of lines) {
    const sectionMatch = line.match(/^([A-Za-z][\w-]*):\s*$/);
    if (sectionMatch && !line.startsWith(" ")) {
      section = sectionMatch[1];
      listKey = "";
      continue;
    }
    const keyMatch = line.match(/^\s{2}([A-Za-z][\w-]*):\s*(.*?)\s*$/);
    if (section === "knowledge" && keyMatch && !keyMatch[2]) {
      listKey = keyMatch[1];
      continue;
    }
    const itemMatch = line.match(/^\s{4}-\s*(.*?)\s*$/);
    if (section === "knowledge" && listKey && itemMatch) {
      const item = itemMatch[1].replace(/^(['"])(.*)\1$/, "$2");
      if (listKey === "sourceRoots") config.sourceRoots.push(item);
      if (listKey === "ignore") config.ignore.push(item);
      continue;
    }
    if (line.trim() && !line.trimStart().startsWith("#") && !line.match(/^\s{4}-/)) {
      listKey = "";
    }
  }
  return {
    sourceRoots: config.sourceRoots.length ? config.sourceRoots : defaults.sourceRoots,
    ignore: [...DEFAULT_IGNORES, ...config.ignore],
  };
}

function matchesIgnore(relative, name, patterns) {
  const segments = relative.split("/");
  for (const pattern of patterns) {
    const normalized = pattern.replace(/\\/g, "/").replace(/^\.\/+/, "").replace(/\/+$/, "");
    if (!normalized) continue;
    if (!normalized.includes("/") && segments.includes(normalized)) return true;
    if (normalized.includes("*")) {
      const regex = new RegExp(`^${normalized.split("*").map((part) =>
        part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join(".*")}(?:/.*)?$`);
      if (regex.test(relative) || regex.test(name)) return true;
    } else if (relative === normalized || relative.startsWith(`${normalized}/`)) {
      return true;
    }
  }
  return false;
}

function classifySource(relative) {
  const name = path.posix.basename(relative).toLowerCase();
  const extension = path.posix.extname(name);
  const normalized = relative.toLowerCase();
  if (/^knowledge\/sources\/business\//.test(normalized) || normalized.includes("/knowledge/sources/business/")) return "business";
  if (/^knowledge\/sources\/architecture\//.test(normalized) || normalized.includes("/knowledge/sources/architecture/")) return "architecture";
  if (/^knowledge\/sources\/infrastructure\//.test(normalized) || normalized.includes("/knowledge/sources/infrastructure/")) return "infrastructure";
  if (/^knowledge\/sources\/data\//.test(normalized) || normalized.includes("/knowledge/sources/data/")) return "data";
  if (/^knowledge\/sources\/operations\//.test(normalized) || normalized.includes("/knowledge/sources/operations/")) return "operations";
  if (/^knowledge\/sources\/external\//.test(normalized) || normalized.includes("/knowledge/sources/external/")) return "external";
  if (/(^|\/)(adr|adrs|decisions)(\/|$)|(^|[-_])(adr|decision)([-_.]|$)/.test(normalized)) return "decisions";
  if (/(^|\/)(logs?|telemetry)(\/|$)|\.(log|jsonl|ndjson)$/.test(normalized)) return "logs";
  if (/openapi|swagger|\.proto$|\.graphql$|\.gql$/.test(normalized)) return "api-contracts";
  if (/(^|\/)(\.github\/workflows|\.gitlab-ci|\.circleci|azure-pipelines|jenkinsfile)/.test(normalized)) return "pipelines";
  if (/(^|\/)(test|tests|spec|specs)(\/|$)|\.(test|spec)\.[^.]+$|\.tests\.ps1$/.test(normalized) ||
      /^test_.+\.py$|^.+_test\.py$|^.+tests?\.cs$/.test(name)) return "tests";
  if (/\.(tf|tfvars|bicep|bicepparam|dockerfile)$/.test(name) || name === "dockerfile" ||
      /(^|\/)(terraform|infra|infrastructure|k8s|kubernetes)(\/|$)/.test(normalized)) return "infrastructure";
  if (/\.(sql|prisma|dbml)$/.test(name) || /(^|\/)(migrations|schema|schemas)(\/|$)/.test(normalized)) return "database";
  if (/\.(md|mdx|txt|rst|adoc)$/.test(extension) || ["license", "readme", "changelog", "makefile"].includes(name)) return "documentation";
  if (/\.(json|jsonc|json5|ya?ml|toml|ini|cfg|conf|xml|properties|env|editorconfig)$/.test(name)) return "configuration";
  if (/\.(csv|tsv|parquet|avro)$/.test(name)) return "data";
  if (DOCUMENT_EXTENSIONS.has(extension)) return "office-documents";
  if (TEXT_EXTENSIONS.has(extension) || ["dockerfile", "makefile", "jenkinsfile"].includes(name)) return "source-code";
  return "unknown";
}

