"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { recordEvent } = require("../../core/src/telemetry");
const { refreshWorkspaceIndex } = require("../../spec-engine/src/lifecycle");

const GENERATED_MARKER = "<!-- Generated by MCPEE; do not edit this file directly. -->";
const OUTPUTS = [
  "docs/generated/project-overview.md",
  "docs/generated/source-catalog.md",
  "docs/generated/components.md",
  "docs/generated/architecture-map.md",
  "docs/generated/apis-and-data.md",
  "docs/generated/infrastructure.md",
  "docs/generated/testing.md",
  "docs/generated/operations.md",
  "docs/generated/decisions.md",
  "docs/generated/quality-and-operations.md",
];

function resolveManifest(root) {
  const file = path.join(root, "knowledge/traceability/source-manifest.json");
  if (!fs.existsSync(file)) throw new Error("Source manifest is missing; run mcpee sync before generating documentation");
  const manifest = JSON.parse(fs.readFileSync(file, "utf8"));
  if (manifest.generated_by !== "mcpee" || !Array.isArray(manifest.sources)) {
    throw new Error(`Invalid or user-owned source manifest: ${file}`);
  }
  return manifest;
}

function groupSources(sources) {
  const groups = new Map();
  for (const source of sources) {
    const list = groups.get(source.category) || [];
    list.push(source);
    groups.set(source.category, list);
  }
  return [...groups.entries()].sort(([left], [right]) => left.localeCompare(right));
}

function sourceLink(source) {
  return `- [\`${source.path.replace(/[\[\]]/g, "")}\`](../../${source.path.replace(/[\[\]]/g, "")}) — ${source.status}; SHA-256 \`${source.sha256 || "unavailable"}\`.`;
}

function extractedEvidence(root, source) {
  if (!["processed", "unchanged"].includes(source.status)) return null;
  const relative = typeof source.extracted_path === "string"
    ? source.extracted_path.replace(/\\/g, "/")
    : "";
  if (!relative.startsWith("knowledge/extracted/") ||
      relative.split("/").some((part) => part === "..")) {
    throw new Error(`Processed source has no safe extracted metadata path: ${source.path}`);
  }
  const absolute = path.resolve(root, relative);
  const fromRoot = path.relative(root, absolute);
  if (!fromRoot || fromRoot === ".." || fromRoot.startsWith(`..${path.sep}`) ||
      path.isAbsolute(fromRoot)) {
    throw new Error(`Extracted metadata path escapes the project: ${source.path}`);
  }
  let current = root;
  for (const part of fromRoot.split(path.sep)) {
    current = path.join(current, part);
    let stat;
    try {
      stat = fs.lstatSync(current);
    } catch (error) {
      if (error.code === "ENOENT" || error.code === "ENOTDIR") {
        throw new Error(`Extracted metadata is missing for ${source.path}: ${relative}`);
      }
      throw error;
    }
    if (stat.isSymbolicLink()) {
      throw new Error(`Extracted metadata cannot follow a symbolic link: ${relative}`);
    }
  }
  const metadata = JSON.parse(fs.readFileSync(absolute, "utf8"));
  if (metadata.generated_by !== "mcpee" || metadata.source_path !== source.path ||
      metadata.sha256 !== source.sha256 || !Array.isArray(metadata.headings) ||
      !Array.isArray(metadata.symbols)) {
    throw new Error(`Extracted metadata does not match source evidence: ${source.path}`);
  }
  return metadata;
}

function evidenceSummary(root, source) {
  const metadata = extractedEvidence(root, source);
  if (!metadata) return "";
  const clean = (value) => value.replace(/[` \r\n]/g, " ").trim();
  const details = [];
  const headings = metadata.headings
    .slice(0, 3)
    .map((heading) => clean(heading.title || ""))
    .filter(Boolean);
  const symbols = metadata.symbols
    .slice(0, 5)
    .map((symbol) => clean(typeof symbol === "string" ? symbol : ""))
    .filter(Boolean);
  const fields = (metadata.tabular_fields || [])
    .slice(0, 10)
    .map((field) => clean(field.name || ""))
    .filter(Boolean);
  if (headings.length) details.push(`headings: ${headings.map((item) => `\`${item}\``).join(", ")}`);
  if (symbols.length) details.push(`symbols: ${symbols.map((item) => `\`${item}\``).join(", ")}`);
  if (fields.length) details.push(`table fields: ${fields.map((item) => `\`${item}\``).join(", ")}`);
  return details.length ? ` Extracted evidence — ${details.join("; ")}.` : "";
}

function sourceEvidenceLink(root, source) {
  return `${sourceLink(source)}${evidenceSummary(root, source)}`;
}

function projectOverview(sources) {
  const processed = sources.filter((source) => source.status === "processed" || source.status === "unchanged").length;
  const needsTool = sources.filter((source) => source.status === "requires-tool").length;
  const failures = sources.filter((source) => source.status === "failed").length;
  return `# Project knowledge overview

${GENERATED_MARKER}

This report is generated from MCPEE's local source manifest. It is an inventory,
not a replacement for the original sources.

- Discovered sources: ${sources.length}
- Processed or unchanged: ${processed}
- Waiting for a local tool: ${needsTool}
- Processing failures: ${failures}

## Sources by category

${groupSources(sources).map(([category, entries]) =>
  `- **${category}:** ${entries.length}`).join("\n") || "- No supported sources discovered."}

## Coverage notes

MCPEE only reports sources it discovered and processors that actually completed.
An unavailable processor, unsupported format, failed extraction, or empty source
set must not be interpreted as proof that the project contains no such material.
`;
}

function sourceCatalog(sources) {
  return `# Source catalog

${GENERATED_MARKER}

Each listed path points back to the project source and its content checksum.

${groupSources(sources).map(([category, entries]) =>
  `## ${category}\n\n${entries.slice(0, 200).map(sourceLink).join("\n") || "- None."}`).join("\n\n") || "No supported sources discovered."}
`;
}

function architectureMap(root, sources) {
  const relevant = sources.filter((source) =>
    ["architecture", "decisions", "infrastructure", "database", "api-contracts", "source-code"].includes(source.category));
  const group = groupSources(relevant);
  return `# Architecture source map

${GENERATED_MARKER}

This is a traceable file inventory; it does not infer runtime topology or claim
relationships that were not extracted.

${group.map(([category, entries]) =>
  `## ${category}\n\n${entries.slice(0, 100).map((source) =>
    `${sourceEvidenceLink(root, source)} Processor: \`${source.processor}\`.`).join("\n") || "- None."}`).join("\n\n") || "No architecture-related sources were discovered."}
`;
}

function qualityAndOperations(root, sources) {
  const relevant = sources.filter((source) =>
    ["tests", "pipelines", "configuration", "operations", "logs"].includes(source.category));
  return `# Quality and operations source map

${GENERATED_MARKER}

This inventory links to test, pipeline, configuration, log, and operational source
files. It does not claim that tests passed or deployments are healthy.

${groupSources(relevant).map(([category, entries]) =>
  `## ${category}\n\n${entries.slice(0, 100).map((source) =>
    sourceEvidenceLink(root, source)).join("\n") || "- None."}`).join("\n\n") || "No quality or operations sources were discovered."}
`;
}

function categorizedSourceMap(title, description, sources, categories, root, limit = 100) {
  const relevant = sources.filter((source) => categories.includes(source.category));
  const groups = groupSources(relevant);
  return `# ${title}

${GENERATED_MARKER}

${description}

${groups.map(([category, entries]) =>
  `## ${category}\n\n${entries.slice(0, limit).map((source) =>
    sourceEvidenceLink(root, source)).join("\n") || "- None."}`).join("\n\n") ||
  "No matching sources were discovered."}
`;
}

function writeOwned(root, relative, contents) {
  const absolute = path.resolve(root, relative);
  const rel = path.relative(path.resolve(root), absolute);
  if (rel === ".." || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel)) {
    throw new Error(`Generated documentation path escapes project root: ${relative}`);
  }
  let current = path.resolve(root);
  for (const part of rel.split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink()) {
      throw new Error(`Refusing to write generated documentation through symbolic link: ${current}`);
    }
  }
  if (fs.existsSync(absolute)) {
    const currentContents = fs.readFileSync(absolute, "utf8");
    if (currentContents === contents) return "unchanged";
    if (!currentContents.split(/\r?\n/).includes(GENERATED_MARKER)) return "preserved";
  }
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  const temporary = `${absolute}.${process.pid}.tmp`;
  try {
    fs.writeFileSync(temporary, contents, "utf8");
    fs.renameSync(temporary, absolute);
  } catch (error) {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
    throw error;
  }
  return "written";
}

function generateProjectDocumentation(projectRoot) {
  const root = path.resolve(projectRoot);
  const manifest = resolveManifest(root);
  const sources = manifest.sources;
  const content = new Map([
    [OUTPUTS[0], projectOverview(sources)],
    [OUTPUTS[1], sourceCatalog(sources)],
    [OUTPUTS[2], categorizedSourceMap(
      "Project components",
      "This source map lists implementation and configuration evidence. It does not infer component boundaries or runtime dependencies.",
      sources,
      ["source-code", "configuration", "database", "api-contracts"],
      root,
    )],
    [OUTPUTS[3], architectureMap(root, sources)],
    [OUTPUTS[4], categorizedSourceMap(
      "APIs and data",
      "This inventory links to discovered API contracts, schemas, database definitions, and structured data. It does not infer undocumented contracts.",
      sources,
      ["api-contracts", "database", "data"],
      root,
    )],
    [OUTPUTS[5], categorizedSourceMap(
      "Infrastructure",
      "This inventory links to infrastructure sources and their recorded processing status. It does not infer deployed topology.",
      sources,
      ["infrastructure"],
      root,
    )],
    [OUTPUTS[6], categorizedSourceMap(
      "Testing",
      "This inventory links to discovered tests and records source status only; it is not a test result or coverage report.",
      sources,
      ["tests"],
      root,
    )],
    [OUTPUTS[7], categorizedSourceMap(
      "Operations",
      "This inventory links to operational configuration and pipeline sources. It does not claim that deployments or services are healthy.",
      sources,
      ["operations", "pipelines", "configuration", "logs"],
      root,
    )],
    [OUTPUTS[8], categorizedSourceMap(
      "Decisions",
      "This inventory links only to discovered decision records. It does not infer approval, status, or rationale beyond each source.",
      sources,
      ["decisions"],
      root,
    )],
    [OUTPUTS[9], qualityAndOperations(root, sources)],
  ]);
  const counts = { written: 0, unchanged: 0, preserved: 0 };
  for (const [relative, body] of content) counts[writeOwned(root, relative, body)] += 1;
  const workspace = refreshWorkspaceIndex(root);
  recordEvent(root, {
    event_name: "documentation.generated",
    attributes: {
      source_count: sources.length,
      written: counts.written,
      unchanged: counts.unchanged,
      preserved: counts.preserved,
    },
  });
  return { counts, files: OUTPUTS, workspace };
}

module.exports = { generateProjectDocumentation, OUTPUTS, GENERATED_MARKER };
