function readCapabilityState(projectRoot) {
  const filePath = safeProjectPath(projectRoot, CAPABILITY_STATE_PATH);
  if (!fs.existsSync(filePath)) return null;
  if (!isOwnedGeneratedFile(filePath)) {
    throw new Error(`Refusing to read user-owned capability state: ${filePath}`);
  }
  let state;
  try {
    state = JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    throw new Error(`Cannot read MCPEE capability state: ${error.message}`);
  }
  if (state.schema_version !== 1 || state.generated_by !== "mcpee" ||
      !state.overrides || typeof state.overrides !== "object" ||
      Object.entries(state.overrides).some(([type, override]) =>
        !Object.hasOwn(CAPABILITY_COLLECTIONS, type) ||
        !override || typeof override !== "object" ||
        ["added", "removed"].some((key) =>
          !Array.isArray(override[key]) ||
          override[key].some((id) => typeof id !== "string")))) {
    throw new Error(`Invalid MCPEE capability state: ${filePath}`);
  }
  return state;
}

function resolveCapabilityAssets(catalog, detectedAssets, state) {
  const overrides = state?.overrides || {};
  const selected = {};
  for (const [type, collection] of Object.entries(CAPABILITY_COLLECTIONS)) {
    const available = new Set(catalog[collection].map((item) => item.id));
    const override = overrides[type] || { added: [], removed: [] };
    const unknown = [...(override.added || []), ...(override.removed || [])]
      .filter((id) => !available.has(id));
    if (unknown.length) {
      throw new Error(`MCPEE capability state references unknown ${type}: ${unknown.join(", ")}`);
    }
    selected[collection] = new Set([
      ...(detectedAssets[collection] || []),
      ...(override.added || []),
    ].filter((id) => !(override.removed || []).includes(id)));
  }

  const addedAgents = new Set(selected.agents);
  const addedWorkflows = new Set(selected.workflows);
  for (const playbookId of selected.playbooks) {
    const playbook = catalog.playbooks.find((item) => item.id === playbookId);
    for (const workflowId of playbook.workflows) addedWorkflows.add(workflowId);
  }
  for (const workflow of catalog.workflows) {
    if (addedWorkflows.has(workflow.id)) addedAgents.add(workflow.agent);
  }
  selected.agents = addedAgents;
  selected.workflows = addedWorkflows;

  for (const agent of catalog.agents) {
    if (!selected.agents.has(agent.id)) continue;
    for (const skillId of agent.skills) selected.skills.add(skillId);
    for (const patternId of agent.patterns || []) selected.patterns.add(patternId);
    for (const workflow of catalog.workflows.filter((item) => item.agent === agent.id)) {
      if (detectedAssets.workflows.includes(workflow.id) ||
          !(overrides.workflow?.removed || []).includes(workflow.id)) {
        selected.workflows.add(workflow.id);
      }
    }
  }
  for (const workflow of catalog.workflows) {
    if (!selected.workflows.has(workflow.id)) continue;
    for (const skillId of workflow.skills) selected.skills.add(skillId);
    for (const patternId of workflow.patterns || []) selected.patterns.add(patternId);
  }

  for (const [type, collection] of Object.entries(CAPABILITY_COLLECTIONS)) {
    const excluded = new Set(overrides[type]?.removed || []);
    for (const id of excluded) selected[collection].delete(id);
  }
  return Object.fromEntries(Object.entries(selected).map(([collection, ids]) => [
    collection,
    [...ids].sort((left, right) => left.localeCompare(right)),
  ]));
}

function capabilityDefaults(catalog, detectedAssets, state) {
  return resolveCapabilityAssets(catalog, detectedAssets, state);
}

function initialCapabilityAssets(catalog, detectedAssets) {
  return Object.fromEntries(Object.values(CAPABILITY_COLLECTIONS).map((collection) => [
    collection,
    detectedAssets[collection] || [],
  ]));
}

function createInitialCapabilityState(agentIds) {
  if (!Array.isArray(agentIds) || agentIds.some((id) => typeof id !== "string")) {
    throw new Error("Initial agent selection must be an array of catalog agent IDs.");
  }
  const { catalog, digest } = readCatalog();
  const available = new Set(catalog.agents.map((agent) => agent.id));
  const selected = new Set(agentIds);
  if (selected.size !== agentIds.length) {
    throw new Error("Initial agent selection cannot contain duplicate IDs.");
  }
  const unknown = [...selected].filter((id) => !available.has(id));
  if (unknown.length) {
    throw new Error(`Initial agent selection contains unknown IDs: ${unknown.join(", ")}`);
  }
  const workflows = catalog.workflows.filter((workflow) => selected.has(workflow.agent));
  const workflowIds = new Set(workflows.map((workflow) => workflow.id));
  const skills = new Set([
    ...catalog.agents.filter((agent) => selected.has(agent.id)).flatMap((agent) => agent.skills),
    ...workflows.flatMap((workflow) => workflow.skills),
  ]);
  const patterns = new Set([
    ...catalog.agents.filter((agent) => selected.has(agent.id)).flatMap((agent) => agent.patterns || []),
    ...workflows.flatMap((workflow) => workflow.patterns || []),
  ]);
  const selectedIds = {
    agent: selected,
    workflow: workflowIds,
    skill: skills,
    pattern: patterns,
  };
  const overrides = {};
  for (const [type, ids] of Object.entries(selectedIds)) {
    const entries = catalog[CAPABILITY_COLLECTIONS[type]];
    overrides[type] = {
      added: [...ids].sort((left, right) => left.localeCompare(right)),
      removed: entries.map((entry) => entry.id)
        .filter((id) => !ids.has(id))
        .sort((left, right) => left.localeCompare(right)),
    };
  }
  return {
    schema_version: 1,
    generated_by: "mcpee",
    catalog_sha256: digest,
    updated_at: new Date().toISOString(),
    overrides,
  };
}

function selectedCatalog(catalog, assets) {
  const selected = { ...catalog };
  for (const [type, collection] of Object.entries(CAPABILITY_COLLECTIONS)) {
    const enabled = new Set(assets[collection]);
    selected[collection] = catalog[collection].filter((item) => enabled.has(item.id));
  }
  selected.agents = selected.agents.map((agent) => ({
    ...agent,
    skills: agent.skills.filter((id) => assets.skills.includes(id)),
    patterns: (agent.patterns || []).filter((id) => assets.patterns.includes(id)),
  }));
  selected.workflows = selected.workflows.map((workflow) => ({
    ...workflow,
    skills: workflow.skills.filter((id) => assets.skills.includes(id)),
    patterns: (workflow.patterns || []).filter((id) => assets.patterns.includes(id)),
  }));
  return selected;
}

function readInstalledCatalog(projectRoot) {
  const { catalog } = readCatalog();
  const state = readCapabilityState(projectRoot);
  if (!state) return catalog;
  const detected = detectProjectCapabilities(projectRoot, catalog);
  return selectedCatalog(catalog, capabilityDefaults(
    catalog,
    initialCapabilityAssets(catalog, detected.assets),
    state,
  ));
}

function capabilityRegistry(projectRoot, catalog = readCatalog().catalog) {
  const detected = detectProjectCapabilities(projectRoot, catalog);
  const state = readCapabilityState(projectRoot);
  const defaults = initialCapabilityAssets(catalog, detected.assets);
  const assets = capabilityDefaults(catalog, defaults, state);
  const items = [];
  for (const [type, collection] of Object.entries(CAPABILITY_COLLECTIONS)) {
    const installed = new Set(assets[collection]);
    for (const entry of catalog[collection]) {
      items.push({
        type,
        id: entry.id,
        description: entry.description,
        status: installed.has(entry.id)
          ? (defaults[collection]?.includes(entry.id) ? "detected-installed" : "installed")
          : "available",
        dependencies: type === "agent"
          ? [...entry.skills]
          : type === "workflow" ? [entry.agent, ...entry.skills]
            : type === "playbook" ? [...entry.workflows] : [],
      });
    }
  }
  for (const collection of ["policies", "tool_capabilities"]) {
    for (const entry of catalog[collection]) {
      items.push({
        type: collection === "policies" ? "policy" : "tool-capability",
        id: entry.id,
        description: entry.description,
        status: "core",
        dependencies: [],
      });
    }
  }
  return {
    schema_version: 1,
    generated_by: "mcpee",
    catalog_sha256: readCatalog().digest,
    detected_technologies: detected.detected_technologies,
    scan: detected.scan,
    defaults,
    items: items.sort((left, right) =>
      left.type.localeCompare(right.type) || left.id.localeCompare(right.id)),
    assets,
    state: state || {
      schema_version: 1,
      generated_by: "mcpee",
      overrides: {},
    },
  };
}

function setCapabilityOverride(state, type, id, installed) {
  const overrides = state.overrides[type] || { added: [], removed: [] };
  overrides.added = [...new Set(overrides.added || [])].filter((item) => item !== id);
  overrides.removed = [...new Set(overrides.removed || [])].filter((item) => item !== id);
  if (installed) overrides.added.push(id);
  else overrides.removed.push(id);
  overrides.added.sort();
  overrides.removed.sort();
  state.overrides[type] = overrides;
}

function manageCapability(projectRoot, action, type, id) {
  const root = path.resolve(projectRoot);
  const { catalog } = readCatalog();
  const registry = capabilityRegistry(root, catalog);
  const item = registry.items.find((entry) => entry.type === type && entry.id === id);
  if (!item) throw new Error(`Unknown ${type} capability '${id}'. Use 'mcpee capabilities list' to see available IDs.`);
  if (item.status === "core") {
    throw new Error(`'${id}' is a core ${type} and cannot be managed individually.`);
  }
  const current = item.status !== "available";
  if (action === "install" && current) {
    return { action, type, id, status: "already-installed", changes: { created: 0, updated: 0, removed: 0 } };
  }
  if (action === "remove" && !current) {
    return { action, type, id, status: "not-installed", changes: { created: 0, updated: 0, removed: 0 } };
  }
  if (action === "update" && !current) throw new Error(`Cannot update ${type} '${id}': it is not installed.`);

  const state = registry.state;
  const statePath = CAPABILITY_STATE_PATH;
  state.overrides ||= {};
  if (action === "install") {
    setCapabilityOverride(state, type, id, true);
    if (type === "agent") {
      for (const workflow of catalog.workflows.filter((entry) => entry.agent === id)) {
        setCapabilityOverride(state, "workflow", workflow.id, true);
      }
    } else if (type === "workflow") {
      const workflow = catalog.workflows.find((entry) => entry.id === id);
      setCapabilityOverride(state, "agent", workflow.agent, true);
    } else if (type === "playbook") {
      const playbook = catalog.playbooks.find((entry) => entry.id === id);
      for (const workflowId of playbook.workflows) {
        setCapabilityOverride(state, "workflow", workflowId, true);
        const workflow = catalog.workflows.find((entry) => entry.id === workflowId);
        setCapabilityOverride(state, "agent", workflow.agent, true);
      }
    }
  }
  if (action === "remove") {
    const dependents = registry.items.filter((candidate) =>
      candidate.status !== "available" && candidate.id !== id &&
      capabilityDependsOn(candidate, item, catalog));
    if (dependents.length) {
      throw new Error(`Cannot remove ${type} '${id}' while installed capabilities depend on it: ${
        dependents.map((dependent) => `${dependent.type}/${dependent.id}`).join(", ")
      }. Remove those capabilities first.`);
    }
    setCapabilityOverride(state, type, id, false);
    if (type === "agent") {
      for (const workflow of catalog.workflows.filter((entry) =>
        entry.agent === id && registry.defaults.workflows.includes(entry.id) &&
        !(state.overrides.workflow?.added || []).includes(entry.id))) {
        setCapabilityOverride(state, "workflow", workflow.id, false);
      }
    }
    const candidateAssets = capabilityDefaults(catalog, registry.defaults, state);
    const remaining = new Set(candidateAssets[CAPABILITY_COLLECTIONS[type]]);
    if (remaining.has(id)) {
      throw new Error(`Cannot remove ${type} '${id}' while another installed capability depends on it.`);
    }
  }
  state.updated_at = new Date().toISOString();
  const rendered = renderCatalog(root, { capabilityState: state });
  const status = action === "update"
    ? (rendered.counts.updated > 0 ? "updated" : "up-to-date")
    : action === "install" ? "installed" : "removed";
  return {
    action,
    type,
    id,
    status,
    state_path: path.relative(root, statePath).replace(/\\/g, "/"),
    changes: {
      created: rendered.counts.created,
      updated: rendered.counts.updated,
      removed: rendered.counts.removed,
    },
  };
}

function capabilityDependsOn(candidate, target, catalog) {
  if (target.type === "agent" && candidate.type === "workflow") {
    return false;
  }
  if (target.type === "agent" && candidate.type === "playbook") {
    const playbook = catalog.playbooks.find((entry) => entry.id === candidate.id);
    return playbook?.workflows.some((workflowId) =>
      catalog.workflows.find((workflow) => workflow.id === workflowId)?.agent === target.id) || false;
  }
  if (target.type === "skill") {
    if (candidate.type === "agent") {
      return catalog.agents.find((entry) => entry.id === candidate.id)?.skills.includes(target.id) || false;
    }
    if (candidate.type === "workflow") {
      return catalog.workflows.find((entry) => entry.id === candidate.id)?.skills.includes(target.id) || false;
    }
  }
  if (target.type === "workflow" && candidate.type === "playbook") {
    return catalog.playbooks.find((entry) => entry.id === candidate.id)?.workflows.includes(target.id) || false;
  }
  if (target.type === "pattern") {
    if (candidate.type === "agent") {
      return catalog.agents.find((entry) => entry.id === candidate.id)?.patterns?.includes(target.id) || false;
    }
    if (candidate.type === "workflow") {
      return catalog.workflows.find((entry) => entry.id === candidate.id)?.patterns?.includes(target.id) || false;
    }
  }
  return false;
}

function slug(value, label) {
  if (typeof value !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(value)) {
    throw new Error(`Invalid ${label} identifier: ${value}`);
  }
  return value;
}

function readJsonFile(filePath, label) {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    throw new Error(`Cannot read ${label} catalog: ${error.message}`);
  }
}

function validateReferences(values, known, label) {
  if (!Array.isArray(values) || values.some((value) => typeof value !== "string")) {
    throw new Error(`${label} must be a list of identifiers`);
  }
  for (const value of values) {
    if (!known.has(value)) throw new Error(`${label} references unknown identifier '${value}'`);
  }
}

function readSourceAsset(sourcePath, label) {
  if (typeof sourcePath !== "string" || !sourcePath.trim()) {
    throw new Error(`${label} source_path must be a non-empty package- or workspace-relative path`);
  }
  const candidates = [
    path.resolve(PROJECT_ROOT, sourcePath),
    path.resolve(PROJECT_ROOT, sourcePath.replace(/^mcpee[\\/]/, "")),
    path.resolve(PROJECT_ROOT, "..", sourcePath),
  ];
  const absolute = candidates.find((candidate) => {
    const relative = path.relative(PROJECT_ROOT, candidate);
    return relative && relative !== ".." && !relative.startsWith(`..${path.sep}`) &&
      !path.isAbsolute(relative) && fs.existsSync(candidate) && fs.statSync(candidate).isFile();
  });
  if (!absolute) {
    throw new Error(`${label} has an invalid or missing source path`);
  }
  const realRoot = fs.realpathSync(PROJECT_ROOT);
  const realSource = fs.realpathSync(absolute);
  const realRelative = path.relative(realRoot, realSource);
  if (realRelative === ".." || realRelative.startsWith(`..${path.sep}`) || path.isAbsolute(realRelative)) {
    throw new Error(`${label} source resolves outside the MCPEE package`);
  }
  return fs.readFileSync(realSource, "utf8");
}

function sourceBody(sourcePath, label) {
  const source = readSourceAsset(sourcePath, label);
  return source.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, "").trim();
}

function validateEntryCollection(catalog, collection, requiredFields = []) {
  if (!Array.isArray(catalog[collection]) || catalog[collection].length === 0) {
    throw new Error(`Catalog collection '${collection}' must be a non-empty array`);
  }
  const ids = new Set();
  for (const entry of catalog[collection]) {
    slug(entry.id, collection);
    if (ids.has(entry.id)) throw new Error(`Duplicate ${collection} id: ${entry.id}`);
    ids.add(entry.id);
    for (const field of requiredFields) {
      if (typeof entry[field] !== "string" || entry[field].trim().length < 3) {
        throw new Error(`${collection}/${entry.id} requires ${field}`);
      }
    }
  }
  return ids;
}

function readCatalog() {
  const raw = fs.readFileSync(CATALOG_FILE, "utf8");
  let catalog;
  try {
    catalog = JSON.parse(raw);
  } catch (error) {
    throw new Error(`Catalog JSON is invalid: ${error.message}`);
  }
  if (catalog.schema_version !== 1) throw new Error("Unsupported catalog schema_version");
  const coverageContract = readJsonFile(COVERAGE_FILE, "catalog coverage");
  const agentIds = validateEntryCollection(catalog, "agents", ["description", "focus"]);
  const skillIds = validateEntryCollection(catalog, "skills", ["description"]);
  const workflowIds = validateEntryCollection(catalog, "workflows", ["description"]);
  validateEntryCollection(catalog, "policies", ["description"]);
  validateEntryCollection(catalog, "patterns", ["description"]);
  validateEntryCollection(catalog, "templates", ["description"]);
  validateEntryCollection(catalog, "playbooks", ["description"]);
  validateEntryCollection(catalog, "technical_guidance", ["description"]);
  const scorecardIds = validateEntryCollection(catalog, "scorecards", ["description"]);
  validateEntryCollection(catalog, "eval_cases", ["description"]);
  validateEntryCollection(catalog, "prompt_examples", ["description"]);
  validateCatalogCoverage(coverageContract, catalog);
  const toolCapabilityIds = validateEntryCollection(catalog, "tool_capabilities", ["description"]);
  if (!Array.isArray(catalog.tools) ||
      catalog.tools.some((tool) => typeof tool !== "string" || !/^[a-z0-9-]+$/.test(tool))) {
    throw new Error("Catalog tools must be a unique list of non-empty identifiers");
  }
  const toolIds = new Set(catalog.tools);
  if (toolIds.size !== catalog.tools.length) {
    throw new Error("Catalog tools must be a unique list of non-empty identifiers");
  }
  const processorCatalog = readJsonFile(PROCESSORS_FILE, "source processor");
  if (processorCatalog.schema_version !== 1 || !Array.isArray(processorCatalog.processors)) {
    throw new Error("Source processor catalog must have schema_version 1 and a processors array");
  }
  const knowledgeCategories = new Set(
    processorCatalog.processors.flatMap((processor) => processor.categories || []),
  );
  for (const agent of catalog.agents) {
    validateReferences(agent.skills, skillIds, `agents/${agent.id}.skills`);
    validateReferences(agent.patterns ?? [], new Set(catalog.patterns.map((pattern) => pattern.id)), `agents/${agent.id}.patterns`);
    if (agent.supporting_source_paths !== undefined &&
        (!Array.isArray(agent.supporting_source_paths) ||
        agent.supporting_source_paths.some((sourcePath) => typeof sourcePath !== "string" || !sourcePath.trim()))) {
      throw new Error(`agents/${agent.id}.supporting_source_paths must be non-empty package-relative paths`);
    }
    if (agent.supporting_source_paths !== undefined &&
        new Set(agent.supporting_source_paths).size !== agent.supporting_source_paths.length) {
      throw new Error(`agents/${agent.id}.supporting_source_paths must not contain duplicates`);
    }
    validateReferences(agent.tools, toolIds, `agents/${agent.id}.tools`);
    validateReferences(
      Object.hasOwn(agent, "tool_capabilities") ? agent.tool_capabilities : [],
      toolCapabilityIds,
      `agents/${agent.id}.tool_capabilities`,
    );
    validateReferences(agent.collaborates_with, agentIds, `agents/${agent.id}.collaborates_with`);
    if (!Array.isArray(agent.preferred_knowledge) || !agent.preferred_knowledge.length ||
        !Array.isArray(agent.evidence) || !agent.evidence.length) {
      throw new Error(`agents/${agent.id} requires preferred_knowledge and evidence`);
    }
    for (const category of agent.preferred_knowledge) {
      if (category !== "all" && !knowledgeCategories.has(category)) {
        throw new Error(`agents/${agent.id} references unknown knowledge category '${category}'`);
      }
    }
  }
  for (const skill of catalog.skills) {
    validateReferences(skill.used_by, agentIds, `skills/${skill.id}.used_by`);
    if (!Array.isArray(skill.procedure) || skill.procedure.length < 2 ||
        skill.procedure.some((step) => typeof step !== "string" || !step.trim())) {
      throw new Error(`skills/${skill.id} requires a procedural checklist`);
    }
    for (const agent of catalog.agents) {
      if (agent.skills.includes(skill.id) !== skill.used_by.includes(agent.id)) {
        throw new Error(`Skill assignment mismatch between skills/${skill.id} and agents/${agent.id}`);
      }
    }
  }
  for (const workflow of catalog.workflows) {
    if (!agentIds.has(workflow.agent)) throw new Error(`workflows/${workflow.id} references unknown agent '${workflow.agent}'`);
    validateReferences(workflow.skills, skillIds, `workflows/${workflow.id}.skills`);
    validateReferences(workflow.patterns ?? [], new Set(catalog.patterns.map((pattern) => pattern.id)), `workflows/${workflow.id}.patterns`);
    if (!Array.isArray(workflow.entry_conditions) || !workflow.entry_conditions.length ||
        !Array.isArray(workflow.outputs) || !workflow.outputs.length ||
        JSON.stringify(workflow.stages) !== JSON.stringify(EXECUTION_STAGES)) {
      throw new Error(`workflows/${workflow.id} must declare entry_conditions, outputs, and the common execution stages`);
    }
  }
  for (const policy of catalog.policies) {
    if (!["runtime", "rendered-guidance", "runtime-and-rendered-guidance"].includes(policy.enforcement) ||
        typeof policy.evidence !== "string" || !policy.evidence.trim()) {
      throw new Error(`policies/${policy.id} requires enforcement and evidence metadata`);
    }
  }
  for (const pattern of catalog.patterns) {
    if (!Array.isArray(pattern.when_to_use) || !pattern.when_to_use.length ||
        !Array.isArray(pattern.steps) || pattern.steps.length < 2 ||
        !Array.isArray(pattern.anti_patterns) || !pattern.anti_patterns.length) {
      throw new Error(`patterns/${pattern.id} requires use cases, steps, and anti-patterns`);
    }
    if (pattern.technology_keywords !== undefined &&
        (!Array.isArray(pattern.technology_keywords) || !pattern.technology_keywords.length ||
        pattern.technology_keywords.some((keyword) => typeof keyword !== "string" || !keyword.trim()))) {
      throw new Error(`patterns/${pattern.id}.technology_keywords must be non-empty strings`);
    }
  }
  for (const template of catalog.templates) {
    if (typeof template.path !== "string" || !Array.isArray(template.when_to_use) ||
        !template.when_to_use.length || !Array.isArray(template.variables)) {
      throw new Error(`templates/${template.id} requires a path, use cases, and variables`);
    }
    readSourceAsset(template.path, `templates/${template.id}`);
    if (template.variables.some((variable) => typeof variable !== "string" || !variable.trim())) {
      throw new Error(`templates/${template.id} variables must be descriptive strings`);
    }
  }
  for (const playbook of catalog.playbooks) {
    if (typeof playbook.path !== "string" || !Array.isArray(playbook.technology_keywords) ||
        !playbook.technology_keywords.length ||
        playbook.technology_keywords.some((keyword) => typeof keyword !== "string" || !keyword.trim()) ||
        !Array.isArray(playbook.workflows) || !playbook.workflows.length) {
      throw new Error(`playbooks/${playbook.id} requires a path, technology keywords, and workflows`);
    }
    validateReferences(playbook.workflows, workflowIds, `playbooks/${playbook.id}.workflows`);
    const contents = readSourceAsset(playbook.path, `playbooks/${playbook.id}`);
    const requiredHeadings = playbook.id === "migration-strategy"
      ? ["Strategy selection", "Required migration controls", "Outputs", "Safety boundaries"]
      : ["Scope", "Procedure", "Outputs", "Safety boundaries"];
    for (const requiredHeading of requiredHeadings) {
      if (!contents.includes(`## ${requiredHeading}`)) {
        throw new Error(`playbooks/${playbook.id} is missing the '## ${requiredHeading}' section`);
      }
    }
  }
  for (const guidance of catalog.technical_guidance) {
    if (typeof guidance.source_path !== "string" ||
        !Array.isArray(guidance.technology_keywords) || !guidance.technology_keywords.length ||
        guidance.technology_keywords.some((keyword) => typeof keyword !== "string" || !keyword.trim())) {
      throw new Error(`technical_guidance/${guidance.id} requires a source path and technology keywords`);
    }
    if (!/https:\/\/\S+/.test(readSourceAsset(guidance.source_path, `technical_guidance/${guidance.id}`))) {
      throw new Error(`technical_guidance/${guidance.id} must cite official or primary documentation`);
    }
  }
  for (const scorecard of catalog.scorecards) {
    if (!Array.isArray(scorecard.criteria) || scorecard.criteria.length < 3 ||
        scorecard.criteria.some((criterion) => typeof criterion !== "string" || !criterion.trim()) ||
        !Array.isArray(scorecard.technology_keywords) ||
        scorecard.technology_keywords.some((keyword) => typeof keyword !== "string" || !keyword.trim())) {
      throw new Error(`scorecards/${scorecard.id} requires technology keywords and at least three criteria`);
    }
  }
  for (const evaluation of catalog.eval_cases) {
    if (!Array.isArray(evaluation.technology_keywords) ||
        evaluation.technology_keywords.some((keyword) => typeof keyword !== "string" || !keyword.trim()) ||
        !Array.isArray(evaluation.expected_behaviors) || !evaluation.expected_behaviors.length ||
        evaluation.expected_behaviors.some((behavior) => typeof behavior !== "string" || !behavior.trim()) ||
        !Array.isArray(evaluation.forbidden_behaviors) || !evaluation.forbidden_behaviors.length ||
        (evaluation.automated_checks !== undefined &&
          (!evaluation.automated_checks ||
            !["required_literals", "forbidden_literals"].every((key) =>
              evaluation.automated_checks[key] === undefined ||
              (Array.isArray(evaluation.automated_checks[key]) &&
                evaluation.automated_checks[key].every((literal) =>
                  typeof literal === "string" && literal.trim().length > 0 && literal.length <= 500))) ||
            Object.keys(evaluation.automated_checks).some((key) =>
              !["required_literals", "forbidden_literals"].includes(key)))) ||
        evaluation.forbidden_behaviors.some((behavior) => typeof behavior !== "string" || !behavior.trim()) ||
        !scorecardIds.has(evaluation.scorecard) ||
        (evaluation.asset_ids !== undefined &&
          (!Array.isArray(evaluation.asset_ids) || !evaluation.asset_ids.length ||
            new Set(evaluation.asset_ids).size !== evaluation.asset_ids.length ||
            evaluation.asset_ids.some((assetId) => typeof assetId !== "string" ||
              (assetId !== "*" && !agentIds.has(assetId))) ||
            (evaluation.asset_ids.includes("*") && evaluation.asset_ids.length !== 1)))) {
      throw new Error(`eval_cases/${evaluation.id} requires keywords, expected/forbidden behavior, and a valid scorecard`);
    }
  }
  for (const example of catalog.prompt_examples) {
    if (typeof example.path !== "string" ||
        !Array.isArray(example.technology_keywords) || !example.technology_keywords.length ||
        example.technology_keywords.some((keyword) => typeof keyword !== "string" || !keyword.trim())) {
      throw new Error(`prompt_examples/${example.id} requires a path and technology keywords`);
    }
    readSourceAsset(example.path, `prompt_examples/${example.id}`);
  }
  for (const collection of ["agents", "skills", "workflows", "patterns"]) {
    for (const entry of catalog[collection]) {
      if (entry.source_path !== undefined) {
        readSourceAsset(entry.source_path, `${collection}/${entry.id}`);
      }
    }
  }
  for (const agent of catalog.agents) {
    for (const sourcePath of agent.supporting_source_paths ?? []) {
      readSourceAsset(sourcePath, `agents/${agent.id}`);
    }
  }
  const toolsCatalog = readJsonFile(TOOL_CATALOG_FILE, "tool");
  if (!Array.isArray(toolsCatalog.tools) || toolsCatalog.schema_version !== 1) {
    throw new Error("Tool catalog must have schema_version 1 and a tools array");
  }
  const executableToolIds = new Set();
  for (const tool of toolsCatalog.tools) {
    slug(tool.id, "tool");
    if (executableToolIds.has(tool.id) || typeof tool.command !== "string" ||
        !Array.isArray(tool.version_args)) {
      throw new Error(`Invalid or duplicate tool definition: ${tool.id}`);
    }
    executableToolIds.add(tool.id);
  }
  for (const id of executableToolIds) {
    if (!toolIds.has(id)) throw new Error(`Catalog tools is missing executable tool '${id}'`);
  }
  if (toolIds.size !== executableToolIds.size) {
    throw new Error("Catalog tools must contain exactly the executable tool identifiers");
  }
  const routing = readJsonFile(ROUTING_RULES_FILE, "routing");
  if (routing.schema_version !== 1 || !workflowIds.has(routing.fallback_workflow) ||
      !Array.isArray(routing.routes) ||
      !Array.isArray(routing.specialists)) {
    throw new Error("Routing catalog has an invalid schema or fallback workflow");
  }
  for (const route of routing.routes) {
    if (!workflowIds.has(route.workflow) || !agentIds.has(route.agent)) {
      throw new Error(`Routing rule references unknown workflow or agent: ${route.workflow}/${route.agent}`);
    }
    validateReferences(route.skills, skillIds, `routing/${route.workflow}.skills`);
    if (!Array.isArray(route.keywords) || !route.keywords.length) {
      throw new Error(`Routing rule '${route.workflow}' requires keywords`);
    }
  }
  for (const specialist of routing.specialists) {
    if (!agentIds.has(specialist.agent) || !Array.isArray(specialist.keywords) ||
        !specialist.keywords.length) {
      throw new Error(`Invalid routing specialist: ${specialist.agent}`);
    }
  }
  const categories = new Set();
  const processorIds = new Set();
  for (const processor of processorCatalog.processors) {
    slug(processor.id, "source processor");
    if (processorIds.has(processor.id)) throw new Error(`Duplicate source processor id: ${processor.id}`);
    processorIds.add(processor.id);
    if (!Array.isArray(processor.categories) || !processor.categories.length ||
        !Array.isArray(processor.formats) || !processor.formats.length ||
        !Array.isArray(processor.outputs) || !processor.outputs.length ||
        !["local", "local-tool-required"].includes(processor.mode) ||
        (processor.mode === "local-tool-required" && !processor.tool)) {
      throw new Error(`Invalid source processor definition: ${processor.id}`);
    }
    for (const category of processor.categories) {
      if (categories.has(category)) throw new Error(`Duplicate source processor category: ${category}`);
      categories.add(category);
    }
    if (processor.tool && !executableToolIds.has(processor.tool)) {
      throw new Error(`Source processor '${processor.id}' references unknown tool '${processor.tool}'`);
    }
  }
  const files = [
    ["catalog/catalog.json", raw],
    ["catalog/coverage.json", fs.readFileSync(COVERAGE_FILE, "utf8")],
    ["catalog/tools/tools.json", fs.readFileSync(TOOL_CATALOG_FILE, "utf8")],
    ["catalog/routing/routing-rules.json", fs.readFileSync(ROUTING_RULES_FILE, "utf8")],
    ["catalog/source-processors/processors.json", fs.readFileSync(PROCESSORS_FILE, "utf8")],
  ];
  for (const template of catalog.templates) {
    files.push([
      `catalog-template/${template.id}/${template.path}`,
      readSourceAsset(template.path, `templates/${template.id}`),
    ]);
  }
  for (const collection of ["agents", "skills", "workflows", "patterns"]) {
    for (const entry of catalog[collection]) {
      if (entry.source_path) {
        files.push([
          `catalog-source/${collection}/${entry.id}/${entry.source_path}`,
          readSourceAsset(entry.source_path, `${collection}/${entry.id}`),
        ]);
      }
    }
    for (const agent of catalog.agents) {
      for (const sourcePath of agent.supporting_source_paths ?? []) {
        files.push([
          `catalog-agent-support/${agent.id}/${sourcePath}`,
          readSourceAsset(sourcePath, `agents/${agent.id}`),
        ]);
      }
    }
  }
  for (const [collection, entries, key] of [
    ["playbook", catalog.playbooks, "path"],
    ["technical-guidance", catalog.technical_guidance, "source_path"],
    ["prompt-examples", catalog.prompt_examples, "path"],
  ]) {
    for (const entry of entries) {
      files.push([
        `catalog-${collection}/${entry.id}/${entry[key]}`,
        readSourceAsset(entry[key], `${collection}/${entry.id}`),
      ]);
    }
  }
  const digest = crypto.createHash("sha256");
  for (const [relative, contents] of files) {
    digest.update(relative).update("\0").update(contents).update("\0");
  }
  return { catalog, coverageContract, raw, digest: digest.digest("hex") };
}

function validateCatalogCoverage(contract, catalog) {
  if (contract.schema_version !== 1 ||
      !Array.isArray(contract.required_asset_categories) ||
      !Array.isArray(contract.technologies)) {
    throw new Error("Catalog coverage contract requires schema_version 1, required_asset_categories, and technologies");
  }
  const categories = new Set(contract.required_asset_categories);
  if (categories.size !== contract.required_asset_categories.length ||
      [...categories].some((category) =>
        !["agents", "skills", "workflows", "technical_guidance", "patterns", "scorecards", "eval_cases", "prompt_examples"].includes(category))) {
    throw new Error("Catalog coverage required_asset_categories contains an unknown or duplicate category");
  }
  const technologyIds = new Set();
  const assetsByCategory = Object.fromEntries(
    [...categories].map((category) => [category, new Set((catalog[category] || []).map((asset) => asset.id))]),
  );
  const validationBases = new Set([
    "dotnet-test-project",
    "python-pytest-config",
    "npm-declared-scripts",
    "project-declared-check",
  ]);
  for (const technology of contract.technologies) {
    if (!technology || typeof technology.id !== "string" ||
        !SUPPORTED_TECHNOLOGIES.includes(technology.id) ||
        technologyIds.has(technology.id) ||
        typeof technology.name !== "string" || !technology.name.trim() ||
        !validationBases.has(technology.validation_basis) ||
        !technology.required_assets || typeof technology.required_assets !== "object" ||
        Array.isArray(technology.required_assets)) {
      throw new Error(`Invalid catalog coverage entry: ${technology?.id || "unknown technology"}`);
    }
    technologyIds.add(technology.id);
    for (const category of categories) {
      const ids = technology.required_assets[category];
      if (!Array.isArray(ids) || !ids.length ||
          ids.some((id) => typeof id !== "string" || !assetsByCategory[category].has(id))) {
        throw new Error(`Catalog coverage ${technology.id} requires existing ${category} asset IDs`);
      }
    }
    if (Object.keys(technology.required_assets).length !== categories.size) {
      throw new Error(`Catalog coverage ${technology.id} must map every required asset category exactly once`);
    }
  }
  const missingTechnologies = SUPPORTED_TECHNOLOGIES.filter((id) => !technologyIds.has(id));
  const unexpectedTechnologies = [...technologyIds].filter((id) => !SUPPORTED_TECHNOLOGIES.includes(id));
  if (missingTechnologies.length || unexpectedTechnologies.length) {
    throw new Error(`Catalog coverage must map every detected technology; missing=${missingTechnologies.join(",") || "none"}, unexpected=${unexpectedTechnologies.join(",") || "none"}`);
  }
}

function summarizeCatalogCoverage(contract) {
  const requiredCategories = contract.required_asset_categories;
  return {
    schema_version: 1,
    status: "mapped",
    status_semantics: contract.status_semantics,
    technology_count: contract.technologies.length,
    required_asset_categories: requiredCategories,
    technologies: contract.technologies.map((technology) => ({
      id: technology.id,
      name: technology.name,
      status: "mapped",
      mapped_asset_categories: requiredCategories.length,
      required_asset_categories: requiredCategories.length,
      required_assets: technology.required_assets,
      validation_basis: technology.validation_basis,
    })),
  };
}

