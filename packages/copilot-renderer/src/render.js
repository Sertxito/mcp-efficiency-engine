const TECHNOLOGY_EXTENSIONS = {
  dotnet: ["cs", "csx", "csproj", "fsproj", "vbproj"],
  python: ["py", "pyi", "pyproject.toml", "requirements*.txt"],
  node: ["js", "mjs", "cjs", "ts", "tsx", "jsx", "json"],
  angular: ["ts", "tsx", "js", "jsx", "html", "css", "scss"],
  react: ["ts", "tsx", "js", "jsx", "html", "css", "scss"],
  azure: ["bicep", "json", "yaml", "yml"],
  aws: ["yaml", "yml", "json", "toml"],
  terraform: ["tf", "tfvars"],
  sql: ["sql", "sqlproj"],
  "cosmos-db": ["cs", "py", "js", "ts", "json"],
  "yaml-pipelines": ["yaml", "yml"],
};

function guidanceTechnologies(guidance, detectedTechnologyIds) {
  const id = guidance.id.toLowerCase();
  const technologyIds = detectedTechnologyIds.filter((technology) => {
    if (id.includes("dotnet") || id.includes("csharp")) return technology === "dotnet";
    if (id.includes("angular")) return technology === "angular";
    if (id.includes("react")) return technology === "react";
    if (id.includes("frontend")) return ["angular", "react"].includes(technology);
    if (id.includes("azure")) return ["azure", "cosmos-db"].includes(technology);
    if (id.includes("aws")) return technology === "aws";
    if (id.includes("terraform")) return technology === "terraform";
    if (id.includes("sql") || id.includes("database")) return ["sql", "cosmos-db"].includes(technology);
    if (id.includes("node")) return technology === "node";
    if (id.includes("python")) return technology === "python";
    return true;
  });
  return technologyIds.length ? technologyIds : detectedTechnologyIds;
}

